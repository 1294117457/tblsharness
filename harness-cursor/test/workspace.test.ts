const DSN = 'postgres://reader:example-secret@db.example.test:5432/app?sslmode=disable';

describe('dsn handling', () => {
  it('strips the dsn from a tbls config and keeps comments', () => {
    const input = `# generated by tbls\n\ndsn: ${DSN}\n# where docs go\ndocPath: doc/schema\n`;
    const { text, dsn } = stripDsnFromTblsConfig(input);
    expect(dsn).toBe(DSN);
    expect(text).not.toContain('example-secret');
    expect(text).toContain('# generated by tbls');
    expect(text).toContain('# where docs go\ndocPath: doc/schema');
  });

  it('leaves configs without a dsn untouched', () => {
    const input = 'docPath: doc\n';
    expect(stripDsnFromTblsConfig(input)).toEqual({ text: input });
  });

  it('masks passwords', () => {
    expect(maskDsn(DSN)).toBe('postgres://reader:****@db.example.test:5432/app?sslmode=disable');
    const message = `failed to connect ${DSN}; password example-secret rejected`;
    const masked = maskSecret(message, DSN);
    expect(masked).not.toContain('example-secret');
  });
});
